#!/usr/bin/env python3
"""bin2c.py SRC DST NAME SIZE BASE

Turn a ROM image into a C header:  static const uint8_t NAME[SIZE] = {...};

SRC may be
  * a raw binary of exactly SIZE bytes, or
  * a Woz Monitor style hex dump (text), e.g.
        E000: 4C B0 E2 AD 11 D0 10 FB
        E008: ...
    in which case bytes are placed relative to BASE (e.g. 0xE000).
"""
import re
import sys


def main():
    if len(sys.argv) != 6:
        sys.exit(__doc__)
    src, dst, name = sys.argv[1], sys.argv[2], sys.argv[3]
    size, base = int(sys.argv[4], 0), int(sys.argv[5], 0)

    raw = open(src, "rb").read()
    if len(raw) == size:
        data = bytes(raw)
    else:
        try:
            text = raw.decode("ascii")
        except UnicodeDecodeError:
            sys.exit(f"{src}: is {len(raw)} bytes, expected exactly {size} "
                     f"(or a text hex dump starting at ${base:04X})")
        buf = bytearray([0xFF] * size)
        seen = set()
        addr = None
        for line in text.splitlines():
            line = line.strip()
            m = re.match(r"^([0-9A-Fa-f]{4}):(.*)$", line)
            if m:
                addr, rest = int(m.group(1), 16), m.group(2)
            else:
                rest = line
            if addr is None:
                continue
            toks = rest.split()
            if not toks or not all(re.fullmatch(r"[0-9A-Fa-f]{2}", t) for t in toks):
                continue
            for t in toks:
                off = addr - base
                if 0 <= off < size:
                    buf[off] = int(t, 16)
                    seen.add(off)
                addr += 1
        if len(seen) != size:
            sys.exit(f"{src}: hex dump covers {len(seen)} of {size} bytes "
                     f"from ${base:04X}; expected a complete image")
        data = bytes(buf)

    rows = []
    for i in range(0, len(data), 16):
        rows.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    with open(dst, "w") as f:
        f.write(f"/* generated by bin2c.py from {src.split('/')[-1]} - do not edit */\n")
        f.write(f"static const uint8_t {name}[{size}] = {{\n")
        f.write("\n".join(rows))
        f.write("\n};\n")


if __name__ == "__main__":
    main()
